/**
 * ВНУТРІШНІЙ ШЛЯХ — єдина перевірка (17.11, знайдено на стенді).
 *
 * Посилання у сповіщенні й параметр `?next=` приходять ЗЗОВНІ: сповіщення іншій людині може
 * створити будь-хто, хто має акаунт. Стара перевірка «починається з / і не з //» пропускала
 * `/\example.com`: браузер читає зворотну риску як пряму, тобто як адресу чужого сайту. Дотик по
 * такому сповіщенню виводив людину з застосунку на чужий сайт (зручна дорога для підробленої
 * сторінки входу), а та сама адреса в `?next=` валила екран входу в «Щось пішло не так».
 * Те саме робить табуляція чи перенос рядка всередині: браузер їх викидає, і `/<таб>/x.com`
 * стає `//x.com`.
 *
 * Правило: рядок починається з однієї `/`, не містить зворотної риски й керівних символів,
 * і браузер, розібравши його, лишається на нашій адресі.
 */
export function isSafeInternalPath(path: unknown): path is string {
  if (typeof path !== "string" || path.length === 0 || path.length > 2000) return false;
  if (path[0] !== "/" || path[1] === "/") return false;
  // зворотна риска й усе нижче пробілу (таб, перенос рядка) — браузер перетворює їх на «//»
  // eslint-disable-next-line no-control-regex
  if (/[\\\u0000-\u001f\u007f]/.test(path)) return false;
  try {
    const base = "https://app.invalid";
    return new URL(path, base).origin === base;
  } catch {
    return false;
  }
}

/** Безпечний шлях або запасний (типово — корінь застосунку). */
export function safeInternalPath(path: unknown, fallback = "/"): string {
  return isSafeInternalPath(path) ? path : fallback;
}
