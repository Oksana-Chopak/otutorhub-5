/** Гривні на місяць за кожним планом. */
export const PRICE_PER_MONTH = {
  monthly: 299,
  halfyear: 269,
  yearly: 249,
} as const;

/** Разовий платіж за довші плани (грн). */
export const PRICE_TOTAL = {
  monthly: 299,
  halfyear: 269 * 6,   // 1614 грн разово, −10% від місячної
  yearly: 249 * 12,    // 2988 грн разово, −17% від місячної
} as const;

/** Знижка відносно місячного плану, у відсотках (для бейджів «−10%»). */
export const PLAN_DISCOUNT = {
  halfyear: Math.round((1 - PRICE_PER_MONTH.halfyear / PRICE_PER_MONTH.monthly) * 100),
  yearly: Math.round((1 - PRICE_PER_MONTH.yearly / PRICE_PER_MONTH.monthly) * 100),
} as const;

export type PlanKey = keyof typeof PRICE_PER_MONTH;

/** «299 грн» — символ підставляє formatPrice, як велить canon у lib/currency. */
export const priceLabel = (plan: PlanKey): string => formatPrice(PRICE_PER_MONTH[plan], "UAH");
export const totalLabel = (plan: PlanKey): string => formatPrice(PRICE_TOTAL[plan], "UAH");
